CREATE DATABASE IF NOT EXISTS inf_db CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS user_db CHARACTER SET utf8mb4;
CREATE USER IF NOT EXISTS 'inf_user'@'%' IDENTIFIED BY '2323';
CREATE USER IF NOT EXISTS 'user_user'@'%' IDENTIFIED BY '2323';
GRANT ALL PRIVILEGES ON inf_db.* TO 'inf_user'@'%';
GRANT ALL PRIVILEGES ON user_db.* TO 'user_user'@'%';
FLUSH PRIVILEGES;
